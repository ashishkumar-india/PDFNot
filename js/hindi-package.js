    /**
     * Master Entrypoint: Automatically detects and translates ANY Hindi text / encoding to 100% Pure Unicode
     * @param {string} rawStr 
     * @returns {string} Clean, beautiful Unicode Hindi
     */
    toUnicode(rawStr) {
      if (!rawStr || typeof rawStr !== 'string') return rawStr;
      let s = rawStr.normalize('NFC');

      // 1. Chanakya & Walkman Decoders
      s = this.chanakyaToUnicode(s);

      // 2. Government Certificate Specific Decoders
      s = this.decodeGovernmentCertificates(s);

      // 3. Pre-consonant 'i' matra reordering (e.g. 'िव' -> 'वि', 'िक' -> 'कि', 'िन' -> 'नि')
      s = s.replace(/\u093F([\u0915-\u0939])/g, '$1\u093F');

      // 4. Character-level legacy glyph replacements when surrounded by or mixed with Hindi
      if (/[\u0900-\u097F]/.test(s)) {
        s = s
          .replace(/\[\]/g, 'प्र')
          .replace(/\[/g, 'प्र')
          .replace(/\]/g, 'त्र')
          .replace(/7/g, (m, offset, str) => {
            const nextChar = str[offset + 1];
            return (nextChar && /[\u0900-\u097F]/.test(nextChar)) ? 'स्' : '7';
          })
          .replace(/8/g, (m, offset, str) => {
            const prevChar = str[offset - 1];
            const nextChar = str[offset + 1];
            return ((prevChar && /[\u0900-\u097F]/.test(prevChar)) || (nextChar && /[\u0900-\u097F]/.test(nextChar))) ? '्त' : '8';
          })
          .replace(/%/g, '्र')
          .replace(/&/g, (m, offset, str) => {
            const prevChar = str[offset - 1];
            return (prevChar && /[\u0900-\u097F]/.test(prevChar)) ? 'न्द्र' : '&';
          });
      }

      // 5. Smart Compound Word Spacing
      const compoundWordSplits = [
        [/([^\s])केसंबंधमें/g, '$1 के संबंध में'],
        [/([^\s])कार्यालयके/g, '$1 कार्यालय के'],
        [/([^\s])सेविका/g, '$1 सेविका'],
        [/([^\s])पदाधिकारी/g, '$1 पदाधिकारी'],
        [/([^\s])योजना/g, '$1 योजना'],
        [/([^\s])प्रमाणपत्र/g, '$1 प्रमाण-पत्र'],
        [/([^\s])प्रमाण-पत्र/g, '$1 प्रमाण-पत्र'],
        [/([^\s])हैकि/g, '$1 है कि'],
        [/([^\s])हूँकि/g, '$1 हूँ कि'],
        [/([^\s])जाताहै/g, '$1 जाता है'],
        [/([^\s])सकताहै/g, '$1 सकता है']
      ];

      compoundWordSplits.forEach(([pat, rep]) => {
        s = s.replace(pat, rep);
      });

      // 6. Fix Devanagari Matra Detachment & Space Glitches
      s = s
        .replace(/ ([\u0900-\u0903\u093A-\u094F\u0951-\u0957\u0962-\u0963])/g, '$1')
        .replace(/\u094D\s+/g, '\u094D')
        .replace(/\s{2,}/g, ' ')
        .trim();

      return s;
    }
